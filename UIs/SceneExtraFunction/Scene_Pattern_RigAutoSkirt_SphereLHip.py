import maya.cmds as cmds
import maya.api.OpenMaya as om


def _selected_target_positions(sphere_count):
    selected = cmds.ls(selection=True, long=True, flatten=True) or []
    if not selected:
        print("[Sphere match] No target selected; use saved positions")
        return None

    targets = []
    seen = set()
    for entry in selected:
        node = entry.split(".", 1)[0]
        found = cmds.ls(node, long=True, objectsOnly=True) or []
        if not found:
            continue
        node = found[0]
        kind = cmds.nodeType(node)
        if kind not in ("transform", "joint"):
            parent = cmds.listRelatives(node, parent=True, fullPath=True) or []
            if not parent:
                continue
            node = parent[0]
            if cmds.nodeType(node) not in ("transform", "joint"):
                continue
        if node not in seen:
            targets.append(node)
            seen.add(node)

    if not targets:
        raise ValueError("No transform or joint found in the current selection")
    if len(targets) not in (1, sphere_count):
        raise ValueError(
            "{} targets selected for {} spheres; select one target or one "
            "target per sphere".format(len(targets), sphere_count)
        )

    positions = []
    for node in targets:
        pos = list(map(float, cmds.xform(
            node, query=True, worldSpace=True, rotatePivot=True
        )))
        print("[Sphere target] {} world pivot {}".format(node, pos))
        positions.append(pos)
    return positions * sphere_count if len(positions) == 1 else positions


def _match_sphere_to_position(sphere, target_position):
    bounds = cmds.exactWorldBoundingBox(sphere)
    center = [(bounds[i] + bounds[i + 3]) * 0.5 for i in range(3)]
    delta = [target_position[i] - center[i] for i in range(3)]
    cmds.move(*delta, sphere, relative=True, worldSpace=True)

    bounds = cmds.exactWorldBoundingBox(sphere)
    new_center = [(bounds[i] + bounds[i + 3]) * 0.5 for i in range(3)]
    error = max(abs(new_center[i] - target_position[i]) for i in range(3))
    print("[Sphere matched] {} center={} target={} error={:.8g}".format(
        sphere, new_center, target_position, error
    ))
    if error > 1.0e-4:
        cmds.warning("Sphere could not match target position: {}".format(sphere))


def CreateExportedSpheres(data=SPHERE_DATA):
    exported_unit = data["linear_unit"]
    current_unit = cmds.currentUnit(query=True, linear=True)
    if current_unit != exported_unit:
        raise RuntimeError(
            "Linear unit mismatch: exported in {!r}, scene uses {!r}. "
            "Set matching units in Maya before rebuilding.".format(
                exported_unit, current_unit
            )
        )

    items = data["spheres"]
    target_positions = _selected_target_positions(len(items))
    if target_positions is None:
        print("[Sphere placement] No selection: restore saved positions")
    else:
        print("[Sphere placement] Match world-space pivot of selected object(s)")
    created = []
    cmds.undoInfo(openChunk=True, chunkName="CreateExportedSpheres")
    try:
        for index, item in enumerate(items):
            parent = cmds.createNode("transform", name=item["name"])
            selection = om.MSelectionList()
            selection.add(parent)
            parent_object = selection.getDependNode(0)

            cvs = [om.MPoint(*p) for p in item["cvs"]]
            surface = om.MFnNurbsSurface()
            surface_object = surface.create(
                cvs,
                item["knots_u"],
                item["knots_v"],
                item["degree_u"],
                item["degree_v"],
                item["form_u"],
                item["form_v"],
                item["rational"],
                parent_object,
            )
            shape = om.MFnDagNode(surface_object).fullPathName()
            shape = cmds.rename(shape, parent.rsplit("|", 1)[-1] + "Shape")

            cmds.xform(parent, worldSpace=True, matrix=item["world_matrix"])
            cmds.xform(
                parent, worldSpace=True, rotatePivot=item["rotate_pivot_world"],
                preserve=True
            )
            cmds.xform(
                parent, worldSpace=True, scalePivot=item["scale_pivot_world"],
                preserve=True
            )

            if target_positions is not None:
                _match_sphere_to_position(parent, target_positions[index])

            cmds.setAttr(parent + ".visibility", item["visible"])
            cmds.setAttr(shape + ".visibility", item["shape_visible"])

            new_selection = om.MSelectionList()
            new_selection.add(shape)
            new_fn = om.MFnNurbsSurface(new_selection.getDagPath(0))
            if (
                (int(new_fn.degreeInU), int(new_fn.degreeInV),
                 int(new_fn.formInU), int(new_fn.formInV))
                !=
                (item["degree_u"], item["degree_v"],
                 item["form_u"], item["form_v"])
            ):
                cmds.warning("Exported NURBS attributes differ: " + parent)

            old_u = item["uv_domain_u"]
            old_v = item["uv_domain_v"]
            new_u = tuple(new_fn.knotDomainInU)
            new_v = tuple(new_fn.knotDomainInV)
            if any(
                abs(x - y) > 1.0e-7
                for x, y in zip(old_u + old_v, new_u + new_v)
            ):
                cmds.warning("Exported U/V domain differs: " + parent)

            created.append(parent)
            print("[Recreated Sphere] {} -> {}".format(item["original_path"], parent))
    finally:
        cmds.undoInfo(closeChunk=True)

    if created:
        cmds.select(created, replace=True)
    return created


CreateExportedSpheres()
